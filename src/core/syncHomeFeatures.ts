import fs from "fs";
import path from "path";
import { getIrwinCliRoot } from "./packageRoot";
import { loadManifest, listFeatureIds } from "./manifest";
import { readRegistry } from "./registry";

export type FeatureCatalogEntry = {
  id: string;
  version: string;
  description: string;
  requires: string[];
  installCommand: string;
};

export type FeatureCatalog = {
  generatedAt: string;
  irwinCliVersion: string;
  features: FeatureCatalogEntry[];
};

const CATALOG_REL = "configs/irwin/featureCatalog.json";
const RUNTIME_REL = "lib/irwin/homeFeatures.ts";

const HOME_FEATURES_SOURCE = `/**
 * Generated by irwin-cli (syncHomeFeatures).
 * Logic lives in irwin-cli — customize the home view or copy this file to stop regeneration.
 */
import fs from "fs";
import path from "path";
import catalog from "@configs/irwin/featureCatalog.json";
import { rootPath } from "@lib/utils/path";

type FeatureCatalogEntry = {
  id: string;
  version: string;
  description: string;
  requires: string[];
  installCommand: string;
};

type FeatureCatalog = {
  generatedAt: string;
  irwinCliVersion: string;
  features: FeatureCatalogEntry[];
};

export type HomeFeatureRow = FeatureCatalogEntry & {
  enabled: boolean;
  missingRequires: string[];
  canInstall: boolean;
};

function readEnabledFeatureIds(): Set<string> {
  const file = rootPath(".irwin", "features.json");
  if (!fs.existsSync(file)) return new Set();
  try {
    const data = JSON.parse(fs.readFileSync(file, "utf8")) as {
      features?: Array<{ id: string }>;
    };
    return new Set((data.features ?? []).map((f) => f.id));
  } catch {
    return new Set();
  }
}

export function getHomeFeatureRows(): HomeFeatureRow[] {
  const enabled = readEnabledFeatureIds();
  const rows: HomeFeatureRow[] = (catalog as FeatureCatalog).features.map((entry) => {
    const missingRequires = entry.requires.filter((req) => !enabled.has(req));
    return {
      ...entry,
      enabled: enabled.has(entry.id),
      missingRequires,
      canInstall: !enabled.has(entry.id) && missingRequires.length === 0,
    };
  });

  rows.sort((a, b) => {
    if (a.enabled !== b.enabled) return a.enabled ? -1 : 1;
    return a.id.localeCompare(b.id);
  });

  return rows;
}

export function getHomeFeatureSummary(): {
  installed: number;
  total: number;
} {
  const rows = getHomeFeatureRows();
  const installed = rows.filter((r) => r.enabled).length;
  return { installed, total: rows.length };
}
`;

function readCliVersion(): string {
  const pkgPath = path.join(getIrwinCliRoot(), "package.json");
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8")) as { version?: string };
    return pkg.version ?? "0.0.0";
  } catch {
    return "0.0.0";
  }
}

export function buildFeatureCatalog(projectRoot: string): FeatureCatalog {
  const ids = listFeatureIds(projectRoot);
  const features: FeatureCatalogEntry[] = [];

  for (const id of ids) {
    try {
      const manifest = loadManifest(id, projectRoot);
      features.push({
        id: manifest.id,
        version: manifest.version,
        description: manifest.description?.trim() || manifest.id,
        requires: manifest.requires ?? [],
        installCommand: `irwin add ${manifest.id}`,
      });
    } catch {
      /* skip broken manifests */
    }
  }

  features.sort((a, b) => a.id.localeCompare(b.id));

  return {
    generatedAt: new Date().toISOString(),
    irwinCliVersion: readCliVersion(),
    features,
  };
}

export type SyncHomeFeaturesOptions = {
  dryRun?: boolean;
};

export function syncHomeFeatures(
  projectRoot: string,
  options: SyncHomeFeaturesOptions = {},
): { catalogPath: string; runtimePath: string; featureCount: number } {
  const catalog = buildFeatureCatalog(projectRoot);
  const catalogPath = path.join(projectRoot, CATALOG_REL);
  const runtimePath = path.join(projectRoot, RUNTIME_REL);
  const catalogJson = JSON.stringify(catalog, null, 2) + "\n";

  if (options.dryRun) {
    return {
      catalogPath: CATALOG_REL,
      runtimePath: RUNTIME_REL,
      featureCount: catalog.features.length,
    };
  }

  fs.mkdirSync(path.dirname(catalogPath), { recursive: true });
  fs.mkdirSync(path.dirname(runtimePath), { recursive: true });
  fs.writeFileSync(catalogPath, catalogJson, "utf8");
  fs.writeFileSync(runtimePath, HOME_FEATURES_SOURCE, "utf8");

  return {
    catalogPath: CATALOG_REL,
    runtimePath: RUNTIME_REL,
    featureCount: catalog.features.length,
  };
}

/**
 * IRW-FIX-039: the "feature store" home page is opt-in (`irwin new --with-home`). A project has it when the
 * registry says so, or when it already has the generated runtime file (apps created by irwin-cli <= 0.0.4).
 */
export function homeStoreEnabled(projectRoot: string): boolean {
  if (fs.existsSync(path.join(projectRoot, RUNTIME_REL))) return true;
  try {
    return readRegistry(projectRoot).withHome === true;
  } catch {
    return false;
  }
}

/** Regenerate the catalog only for projects that have the home store; returns null otherwise. */
export function syncHomeFeaturesIfEnabled(
  projectRoot: string,
  options: SyncHomeFeaturesOptions = {},
): ReturnType<typeof syncHomeFeatures> | null {
  return homeStoreEnabled(projectRoot) ? syncHomeFeatures(projectRoot, options) : null;
}

/** True when catalog is missing or enabled set may be out of date (registry newer than catalog). */
export function homeFeaturesNeedSync(projectRoot: string): boolean {
  const catalogFile = path.join(projectRoot, CATALOG_REL);
  if (!fs.existsSync(catalogFile)) return true;

  try {
    const catalog = JSON.parse(
      fs.readFileSync(catalogFile, "utf8"),
    ) as FeatureCatalog;
    const registry = readRegistry(projectRoot);
    const catalogIds = new Set(catalog.features.map((f) => f.id));
    const enabledIds = registry.features.map((f) => f.id);

    for (const id of enabledIds) {
      if (!catalogIds.has(id)) return true;
    }

    const generatedAt = Date.parse(catalog.generatedAt);
    for (const entry of registry.features) {
      const addedAt = Date.parse(entry.addedAt);
      if (!Number.isNaN(addedAt) && addedAt > generatedAt) return true;
    }
  } catch {
    return true;
  }

  return !fs.existsSync(path.join(projectRoot, RUNTIME_REL));
}
